/** Icone il cui nome inglese contiene il testo, piu' quelle delle parole italiane che lo contengono (max 30). */
export const searchIcons = (text) => {
  const q = text.trim().toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');
  if (q.length < 2 || iconNames.includes(q)) return [];
  const it = Object.entries(IT).filter(([word]) => word.includes(q)).flatMap(([, names]) => names);
  return [...new Set([...it, ...iconNames.filter(n => n.includes(q))])].filter(n => iconNames.includes(n)).slice(0, 30);
};
